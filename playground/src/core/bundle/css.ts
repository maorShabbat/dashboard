/** Flat token exports for hosts that style DOM UI from the same theme: tokens.json and theme.css. */
import { cssFontStack } from '../fonts';
import type { ResolvedTokens } from '../resolve';
import { TOKEN_DEFS } from '../tokens';
import type { BundleFont } from './types';

const kebab = (s: string) => s.replace(/\./g, '-').replace(/([a-z])([A-Z])/g, '$1-$2').toLowerCase();

export function tokensJson(t: ResolvedTokens): Record<string, number | boolean | string> {
  const out: Record<string, number | boolean | string> = {};
  for (const d of TOKEN_DEFS) if (d.section !== 'sound' && d.section !== 'layers') out[d.key] = t.values[d.key]!;
  return out;
}

/**
 * Lengths in "% cell" are exported as unitless fractions; multiply by `--bangers-cell` (the board cell edge in px, set by
 * your layout code) to get pixels: `width: calc(var(--bangers-cell) * var(--bangers-outline-width))`.
 */
export function themeCss(t: ResolvedTokens, fonts: BundleFont[]): string {
  const lines: string[] = ['/* Generated by BANGERS Theme Studio. Do not edit by hand. */'];
  for (const f of fonts) {
    for (const file of f.files) {
      lines.push(`@font-face { font-family: "${f.family}"; font-weight: ${file.weight}; font-style: ${file.style}; font-display: swap; src: url("../${file.path}") format("${file.format === 'ttf' ? 'truetype' : file.format === 'otf' ? 'opentype' : file.format}"); }`);
    }
  }
  lines.push(':root {', '  --bangers-cell: 100px; /* set from your board layout */');
  for (const d of TOKEN_DEFS) {
    if (d.section === 'sound' || d.section === 'layers' || d.section === 'assets') continue;
    const v = t.values[d.key]!;
    const name = `--bangers-${kebab(d.key)}`;
    if (d.kind === 'number') lines.push(`  ${name}: ${d.unit === 'cell%' ? +(Number(v) / 100).toFixed(4) : v}; /* ${d.unit === 'cell%' ? 'fraction of a cell' : d.unit || 'unitless'} */`);
    else if (d.kind === 'font') {
      const f = fonts.find((x) => x.id === v);
      lines.push(`  ${name}: ${f ? `"${f.family}", ${f.fallback}` : cssFontStack(String(v))};`);
    } else if (d.kind === 'boolean') lines.push(`  ${name}: ${v ? 1 : 0};`);
    else lines.push(`  ${name}: ${v};`);
  }
  lines.push('}', '');
  return lines.join('\n');
}
