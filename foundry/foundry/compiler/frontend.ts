/** Adds the feature events to the template's book event types and handler map (idempotent: states carry the full picture). */
export function patchFeatureEvents(typesSrc: string, handlerSrc: string): { types: string; handlers: string } {
  let t = typesSrc;
  t = replaceOnce(t, 'export type BookEvent =\n', "type BookEventCellMultipliers = {\n\tindex: number;\n\ttype: 'cellMultipliers';\n\tcells: { reel: number; row: number; multiplier: number }[];\n};\n\ntype BookEventMysteryReveal = {\n\tindex: number;\n\ttype: 'mysteryReveal';\n\tsymbol: string;\n\tcells: { reel: number; row: number }[];\n};\n\ntype BookEventWildMultipliers = {\n\tindex: number;\n\ttype: 'wildMultipliers';\n\tcells: { reel: number; row: number; value: number }[];\n};\n\ntype BookEventScatterPay = {\n\tindex: number;\n\ttype: 'scatterPay';\n\tcount: number;\n\tamount: number;\n};\n\ntype BookEventHoldAndWin = {\n\tindex: number;\n\ttype: 'holdAndWin';\n\tid: string;\n\tstart: { reel: number; row: number; value: number }[];\n\tsteps: { respins: number; orbs: { reel: number; row: number; value: number }[] }[];\n\tfull: boolean;\n\tamount: number;\n};\n\ntype BookEventGadgetPanel = {\n\tindex: number;\n\ttype: 'gadgetPanel';\n\tcells: { charge: number; level: number }[];\n\topened: number[];\n};\n\nexport type BookEvent =\n\t| BookEventCellMultipliers\n\t| BookEventGadgetPanel\n\t| BookEventHoldAndWin\n\t| BookEventScatterPay\n\t| BookEventWildMultipliers\n\t| BookEventMysteryReveal\n", 'game/typesBookEvent.ts');
  let h = handlerSrc;
  h = replaceOnce(h, "import { stateGame, stateGameDerived } from './stateGame.svelte';", "import { stateGame, stateGameDerived } from './stateGame.svelte';\nimport { featureHud, resetFeatureHud } from './foundryFeatureHud.svelte';\nimport featureFile from './foundryFeatures.json';", 'game/bookEventHandlerMap.ts');
  h = replaceOnce(h, "\treveal: async (bookEvent: BookEventOfType<'reveal'>, { bookEvents }: BookEventContext) => {\n", "\treveal: async (bookEvent: BookEventOfType<'reveal'>, { bookEvents }: BookEventContext) => {\n\t\tif (bookEvent.gameType === 'basegame') resetFeatureHud();\n", 'game/bookEventHandlerMap.ts');
  h = replaceOnce(h, "\tfreeSpinTrigger: async (bookEvent: BookEventOfType<'freeSpinTrigger'>) => {\n", "\tcellMultipliers: async (bookEvent: BookEventOfType<'cellMultipliers'>) => {\n\t\tfeatureHud.cells = bookEvent.cells;\n\t},\n\tholdAndWin: async (bookEvent: BookEventOfType<'holdAndWin'>) => {\n\t\tconst wait = (ms: number) => new Promise((r) => setTimeout(r, ms));\n\t\tconst sum = (o: { value: number }[]) => o.reduce((a, x) => a + x.value, 0);\n\t\tlet orbs = [...bookEvent.start];\n\t\tfeatureHud.hw = { on: true, orbs, respins: (featureFile as any[]).find((f) => f.id === bookEvent.id)?.respins ?? 3, total: sum(orbs), full: false };\n\t\tawait wait(900);\n\t\tfor (const step of bookEvent.steps) {\n\t\t\torbs = [...orbs, ...step.orbs];\n\t\t\tfeatureHud.hw = { on: true, orbs, respins: step.respins, total: sum(orbs), full: false };\n\t\t\tawait wait(step.orbs.length ? 700 : 350);\n\t\t}\n\t\tfeatureHud.hw = { on: true, orbs, respins: 0, total: bookEvent.amount / 100, full: bookEvent.full };\n\t\tawait wait(1400);\n\t\tfeatureHud.hw = { on: false, orbs: [], respins: 0, total: 0, full: false };\n\t},\n\twildMultipliers: async (bookEvent: BookEventOfType<'wildMultipliers'>) => {\n\t\tfeatureHud.wilds = bookEvent.cells;\n\t},\n\tscatterPay: async () => {\n\t\t// presentation: the setWin event that follows shows the cash the scatters paid\n\t},\n\tmysteryReveal: async () => {\n\t\t// presentation: the reveal event that follows already shows the final board\n\t},\n\tgadgetPanel: async (bookEvent: BookEventOfType<'gadgetPanel'>) => {\n\t\tfeatureHud.gadget = { cells: bookEvent.cells, opened: bookEvent.opened, opens: featureHud.gadget.opens + bookEvent.opened.length };\n\t},\n\tfreeSpinTrigger: async (bookEvent: BookEventOfType<'freeSpinTrigger'>) => {\n\t\tresetFeatureHud();\n", 'game/bookEventHandlerMap.ts');
  h = replaceOnce(h, "\tfreeSpinEnd: async (bookEvent: BookEventOfType<'freeSpinEnd'>) => {\n", "\tfreeSpinEnd: async (bookEvent: BookEventOfType<'freeSpinEnd'>) => {\n\t\tresetFeatureHud();\n", 'game/bookEventHandlerMap.ts');
  return { types: t, handlers: h };
}

const SKIP = new Set(['build', 'node_modules', '.svelte-kit']);

function copyTree(from: string, to: string, skip: (rel: string) => boolean, rel = ''): void {
  fs.mkdirSync(to, { recursive: true });
  for (const e of fs.readdirSync(from, { withFileTypes: true })) {
    const r = rel ? `${rel}/${e.name}` : e.name;
    if (SKIP.has(e.name) || skip(r)) continue;
    const a = path.join(from, e.name);
    const b = path.join(to, e.name);
    if (e.isDirectory()) copyTree(a, b, skip, r);
    else fs.copyFileSync(a, b);
  }
}

export interface FrontendResult {
  appDir: string;
  appName: string;
  devArt: boolean;
  files: string[];
}

export function buildFrontend(o: FrontendOptions): FrontendResult {
  const game = JSON.parse(fs.readFileSync(path.join(o.gameDir, 'build-manifest.json'), 'utf8')) as { game: string; gameType?: string; variableHeights?: boolean; tumble?: boolean };
  const strings = JSON.parse(fs.readFileSync(path.join(o.gameDir, 'strings/en.json'), 'utf8')) as Record<string, unknown>;
  const social = JSON.parse(fs.readFileSync(path.join(o.gameDir, 'strings/sweeps_en.json'), 'utf8'));
  const configFe = JSON.parse(fs.readFileSync(o.frontConfig, 'utf8'));
  const appName = (o.appName ?? game.game).replace(/[^A-Za-z0-9_-]/g, '_');
  const name = String(strings['meta.name']);
  const provider = String(strings['meta.provider'] ?? '');
  // pay anywhere and cluster games emit the same events as the tumbling scatter app; lines and ways have their own sample apps
  const from = path.join(o.webSdk, 'apps', (game.gameType === 'paylines' || game.gameType === 'ways') && !game.tumble ? (game.gameType === 'paylines' ? 'lines' : 'ways') : 'scatter');
  const appDir = path.join(o.webSdk, 'apps', appName);
  if (!fs.existsSync(from)) throw new Error(`${from} not found (need a Web SDK checkout)`);

  fs.rmSync(appDir, { recursive: true, force: true });
  copyTree(from, appDir, (r) => r === 'static/stake-engine-loader.gif' || r === 'static/loader.gif' || r === 'static/assets' || r === 'src/components/I18nTest.svelte');

  const written: string[] = [];
  const put = (rel: string, text: string) => {
    fs.mkdirSync(path.dirname(path.join(appDir, rel)), { recursive: true });
    fs.writeFileSync(path.join(appDir, rel), text);
    written.push(rel);
  };
  const read = (rel: string) => fs.readFileSync(path.join(appDir, rel), 'utf8');

  put('src/game/config.ts', renderFrontConfig(configFe));
  put('src/game/foundryStrings.ts', renderStringsModule(strings, social));
  put('src/game/betModeMeta.ts', BET_MODE_META_TS);
  put('src/game/webfontStub.ts', WEBFONT_STUB_TS);
  const assets = patchAssetUrls(read('src/game/assets.ts'));
  if (assets.changed < 50) throw new Error(`expected the template's asset addresses in src/game/assets.ts, patched ${assets.changed}`);
  put('src/game/assets.ts', assets.text);
  put('src/game/spriteLang.ts', SPRITE_LANG_TS);
  let patchedSprites = 0;
  for (const f of fs.readdirSync(path.join(appDir, 'src/components')).filter((n) => n.endsWith('.svelte'))) {
    const r = patchSpriteLang(read(`src/components/${f}`));
    if (r.changed) {
      put(`src/components/${f}`, r.text);
      patchedSprites += r.changed;
    }
  }
  if (patchedSprites < 4) throw new Error(`expected at least 4 localized sprite keys in the template, patched ${patchedSprites}`);
  if (fs.existsSync(path.join(appDir, 'src/game/constants.ts'))) {
    const paying = Object.keys((configFe.symbols as Record<string, unknown>[]).reduce((a, x) => ({ ...a, ...x }), {})).filter((k) => !['W', 'S', 'M'].includes(k) && /^[HL]/.test(k));
    put('src/game/constants.ts', patchBoardSize(read('src/game/constants.ts'), Number(configFe.numReels), Number((configFe.numRows as number[])[0]), paying));
  }
  if (configFe.numReels && Array.isArray(configFe.numRows) && fs.existsSync(path.join(appDir, 'src/components/BoardFrame.svelte'))) put('src/components/BoardFrame.svelte', patchBoardFrame(read('src/components/BoardFrame.svelte'), Number(configFe.numReels), Number((configFe.numRows as number[])[0])));
  if (from.endsWith('/lines') || from.endsWith('/ways')) put('src/game/utils.ts', patchSymbolLookup(read('src/game/utils.ts')));
  if (game.variableHeights) put('src/components/Symbol.svelte', patchBlankSymbol(read('src/components/Symbol.svelte')));
  if (fs.existsSync(path.join(o.gameDir, 'features.json')) && (JSON.parse(fs.readFileSync(path.join(o.gameDir, 'features.json'), 'utf8')) as { type: string }[]).some((f) => f.type === 'wildMultiplier')) put('src/components/Symbol.svelte', patchWildValue(read('src/components/Symbol.svelte')));
  put('vite.config.js', VITE_CONFIG_JS);
  put('src/app.html', patchAppHtml(read('src/app.html'), o.demo ? { title: o.demo.title } : undefined));
  if (o.demo) {
    put('static/demo-books.json', o.demo.dataJson);
    put('static/demo-rgs.js', o.demo.shimJs);
  }
  put('src/game/foundryFeatureHud.svelte.ts', FEATURE_HUD_STATE_TS);
  put('src/game/foundryFeatures.json', fs.existsSync(path.join(o.gameDir, 'features.json')) ? fs.readFileSync(path.join(o.gameDir, 'features.json'), 'utf8') : '[]\n');
  put('src/components/FoundryFeatureHud.svelte', FEATURE_HUD_SVELTE);
  const fe = patchFeatureEvents(read('src/game/typesBookEvent.ts'), read('src/game/bookEventHandlerMap.ts'));
  put('src/game/typesBookEvent.ts', fe.types);
  put('src/game/bookEventHandlerMap.ts', fe.handlers);
  put('src/components/FoundryLoader.svelte', LOADER_SVELTE);
  put('src/components/FoundryModals.svelte', MODALS_SVELTE);
  put('src/components/FoundryRulesModal.svelte', RULES_MODAL_SVELTE);
  put('src/routes/+layout.svelte', patchLayout(read('src/routes/+layout.svelte'), name));
  put('src/components/Game.svelte', patchGame(read('src/components/Game.svelte'), name, provider));
  const pkg = JSON.parse(read('package.json'));
  pkg.name = appName.replace(/_/g, '-');
  // the app imports pixi.js/unsafe-eval directly, so it depends on the same pixi.js version as the Web SDK's pixi-svelte package
  const pixiSvelte = JSON.parse(fs.readFileSync(path.join(o.webSdk, 'packages/pixi-svelte/package.json'), 'utf8')) as { dependencies?: Record<string, string> };
  const pixiVersion = pixiSvelte.dependencies?.['pixi.js'];
  if (!pixiVersion) throw new Error('packages/pixi-svelte does not depend on pixi.js: cannot pin the CSP-safe module version');
  pkg.dependencies = { ...(pkg.dependencies ?? {}), 'pixi.js': pixiVersion };
  put('package.json', JSON.stringify(pkg, null, '\t') + '\n');

  const devArt = (o.devArt ?? 'link') === 'link';
  if (devArt) fs.symlinkSync(path.join(from, 'static/assets'), path.join(appDir, 'static/assets'), 'dir');
  put(
    'FOUNDRY_APP.md',
    `# ${name}: generated frontend (${appName})\n\nGenerated by the Slot Foundry compiler from the compiled game and the Web SDK \`apps/scatter\` template.\n\n` +
      `- \`src/game/config.ts\`: the Math SDK frontend config for this game (symbols, pays, modes). Regenerate, do not edit.\n` +
      `- \`src/game/foundryStrings.ts\`: keyed strings (English and Stake.US variant).\n` +
      `- No external requests: the Typekit font preload is replaced by a stub (\`vite.config.js\` alias, \`src/game/webfontStub.ts\`); text uses the system font until the game ships its own font from the Engine CDN.\n` +
      `- The Stake Engine loader and the example loader are removed; \`src/components/FoundryLoader.svelte\` is a plain placeholder.\n` +
      `- **devArt: ${devArt}.** ${devArt ? '`static/assets` is a link to the Web SDK sample art. Engine rejects sample assets: replace every file before submission.' : 'No art was provided: add `static/assets` before building.'}\n` +
      `- Still to do (see AI_INSTRUCTIONS.md): unique art and audio, rules screen from the keyed strings, confirmations, social mode wiring, tile assets.\n`,
  );
  return { appDir, appName, devArt, files: written };
}
