/** Use `spriteLang()` for localized sprite keys such as `pressToContinueText_{lang}.png`. Returns the new text and the number of keys changed. */
export function patchSpriteLang(src: string): { text: string; changed: number } {
  let changed = 0;
  let text = src.replace(/key="(\w+)_\{stateUrlDerived\.lang\(\)\}\.png"/g, (_m, name: string) => {
    changed++;
    return `key="${name}_{spriteLang()}.png"`;
  });
  if (changed) text = replaceOnce(text, '<script lang="ts">\n', '<script lang="ts">\n\timport { spriteLang } from \'../game/spriteLang\';\n', 'component with localized sprites');
  return { text, changed };
}

/**
 * The sample builds every asset address as `new URL('../../assets/x', import.meta.url)`, which the bundler leaves for run time because the files live in
 * `static/assets`. At run time that resolves against the script file and lands in the wrong folder unless the game sits at the site root, so any hosting
 * under a sub-path (the artifact host, Engine's `/{game}/{version}/`) gets 404s and a black screen. Resolve against the page address instead.
 */
export function patchAssetUrls(src: string): { text: string; changed: number } {
  let changed = 0;
  const text = src.replace(/new URL\('\.\.\/\.\.\/(assets\/[^']+)', import\.meta\.url\)\.href/g, (_m, rel: string) => {
    changed++;
    return `assetUrl('${rel}')`;
  });
  if (!changed) return { text, changed };
  const helper = `// Resolves against the page address, so the game works wherever it is hosted (root, sub-path, framed). Prerender has no document: a placeholder base is fine there.\nconst assetUrl = (rel: string): string => new URL(rel, typeof document !== 'undefined' ? document.baseURI : 'http://localhost/').href;\n`;
  return { text: helper + text, changed };
}

export function patchAppHtml(src: string, demo?: { title: string }): string {
  let s = src;
  // The sample loads a font stylesheet from Adobe Typekit; Engine requires a static build with no external sources.
  s = replaceOnce(s, /\t\t<link rel="stylesheet" href="https:\/\/use\.typekit\.net\/[^"]+" \/>\n/, '', 'app.html');
  // Disable pinch/double-tap zoom on mobile (checklist).
  s = replaceOnce(s, '<meta name="viewport" content="width=device-width" />', '<meta name="viewport" content="width=device-width, initial-scale=1, maximum-scale=1, user-scalable=no, viewport-fit=cover" />', 'app.html');
  s = replaceOnce(s, 'overflow: hidden; background-color: black', 'overflow: hidden; touch-action: manipulation; background-color: black', 'app.html');
  // The router has no route for ".../index.html" (only for the directory), so a game opened as index.html (Engine's launch URL does this) throws "Not found".
  // Rewrite the address to its directory before the app computes its base path. No reload, relative asset addresses are unchanged.
  s = replaceOnce(
    s,
    '\t\t%sveltekit.head%\n',
    '\t\t<script>\n\t\t\tif (/\\/index\\.html$/.test(location.pathname)) history.replaceState(history.state, "", location.pathname.replace(/index\\.html$/, "") + location.search + location.hash);\n\t\t</script>\n\t\t%sveltekit.head%\n',
    'app.html',
  );
  // The Web SDK asks PixiJS for a WebGPU renderer first (pixi-svelte, preference 'webgpu'). Browsers that have WebGPU then take a path this build is not
  // verified on, and the scene can go black after the first tap. Hide WebGPU so PixiJS uses WebGL, the path the game is tested on.
  s = replaceOnce(
    s,
    '\t\t%sveltekit.head%\n',
    '\t\t<script>\n\t\t\ttry {\n\t\t\t\tObject.defineProperty(navigator, "gpu", { value: undefined, configurable: true });\n\t\t\t} catch (e) {\n\t\t\t\t/* already fixed by the browser: PixiJS will still fall back if WebGPU fails */\n\t\t\t}\n\t\t</script>\n\t\t%sveltekit.head%\n',
    'app.html',
  );
  // The page itself must not scroll (checklist: main game frame is not scrollable), even programmatically.
  if (demo) {
    // Demo build: a page title, and the in-browser RGS stand-in loaded before anything else.
    s = replaceOnce(s, '\t\t<meta charset="utf-8" />\n', `\t\t<meta charset="utf-8" />\n\t\t<title>${demo.title.replace(/[<>&]/g, '')}</title>\n\t\t<script src="%sveltekit.assets%/demo-rgs.js"></script>\n`, 'app.html');
  }
  s = replaceOnce(s, '\t\t%sveltekit.head%\n', '\t\t<style>\n\t\t\t/* The hosted sample font is not loaded (no external requests): its family name maps to the best local sans-serif font. */\n\t\t\t@font-face {\n\t\t\t\tfont-family: "proxima-nova";\n\t\t\t\tsrc: local("Helvetica Neue"), local("Helvetica"), local("Arial"), local("Liberation Sans"), local("DejaVu Sans");\n\t\t\t}\n\t\t\thtml,\n\t\t\tbody {\n\t\t\t\toverflow: hidden;\n\t\t\t\theight: 100%;\n\t\t\t\toverscroll-behavior: none;\n\t\t\t}\n\t\t</style>\n\t\t%sveltekit.head%\n', 'app.html');
  return s;
}

/** The Web SDK app sizes its board from INITIAL_BOARD (reels x rows, padded by one symbol above and below), so the game's own board size must be written there. */
export function patchBoardSize(constantsSrc: string, reels: number, rows: number, symbols: string[]): string {
  const syms = symbols.length ? symbols : ['L1'];
  const board = Array.from({ length: reels }, (_, r) => `\t[\n${Array.from({ length: rows + 2 }, (_, y) => `\t\t{ name: ${JSON.stringify(syms[(r * 2 + y) % syms.length])} },`).join('\n')}\n\t],`).join('\n');
  // the design canvas is 800 high with the controls at the bottom: keep the board about as tall as the template's own
  const m = /export const SYMBOL_SIZE = (\d+);/.exec(constantsSrc);
  if (!m) throw new Error('patch anchor not found in game/constants.ts: SYMBOL_SIZE');
  const size = Math.round(Math.min(Number(m[1]), 520 / rows, 1000 / reels));
  let out = constantsSrc;
  if (size !== Number(m[1])) out = out.replace(m[0], `export const SYMBOL_SIZE = ${size};`);
  const re = /export const INITIAL_BOARD: RawSymbol\[\]\[\] = \[[\s\S]*?\n\];\n/;
  if (!re.test(out)) throw new Error('patch anchor not found in game/constants.ts: INITIAL_BOARD');
  return out.replace(re, () => `export const INITIAL_BOARD: RawSymbol[][] = [\n${board}\n];\n`);
}

/** The board frame picture keeps one aspect ratio (made for 6x5): stretch it to the board's own shape. */
export function patchBoardFrame(src: string, reels: number, rows: number): string {
  if (src.includes('const SPRITE_SCALE = { width: 1.25, height: 0.72 };')) {
    // the lines and ways apps draw a wide frame made for 3 rows; taller boards stretch it down over the extra rows
    if (rows <= 3) return src;
    const h = Math.round((0.72 + Math.min(0.36, 0.09 * (rows - 3))) * 100) / 100;
    return src.replace('const SPRITE_SCALE = { width: 1.25, height: 0.72 };', `const SPRITE_SCALE = { width: 1.25, height: ${h} };`).replace('const SPINE_SCALE = { width: 0.62, height: 0.66 };', `const SPINE_SCALE = { width: 0.62, height: ${Math.round(0.66 * (h / 0.72) * 100) / 100} };`);
  }
  if (!src.includes('const BG_RATIO = 937 / 806;')) return src; // only the scatter app's frame keeps a fixed picture ratio
  const ratio = Math.round((937 / 806) * ((reels / rows) / (6 / 5)) * 1000) / 1000;
  return src.replace('const BG_RATIO = 937 / 806;', `const BG_RATIO = ${ratio};`);
}

